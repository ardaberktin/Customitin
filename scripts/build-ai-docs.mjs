import { readFile, writeFile } from 'node:fs/promises';
const topics = [
  'index',
  'integration',
  'contracts',
  'maintenance',
  'troubleshooting',
  'testing',
  'cli-reference',
];
const chapters = await Promise.all(
  topics.map(
    async (topic) =>
      `<!-- Source: docs/ai/${topic}.md -->\n\n${await readFile(`docs/ai/${topic}.md`, 'utf8')}`,
  ),
);
const result = `<!-- Generated by npm run docs:build. Edit docs/ai/*.md instead. -->\n\n${chapters.join('\n\n---\n\n')}`;
if (process.argv.includes('--check')) {
  if ((await readFile('llms-full.txt', 'utf8')) !== result)
    throw new Error(
      'AI documentation bundle is stale. Run npm run docs:build.',
    );
} else await writeFile('llms-full.txt', result);
